async function seedAll() {
  console.log(`--- Seeding ${ALL_REAL_STARTUPS.length} real Visakhapatnam startups ---`);

  // Write local JSON files
  fs.writeFileSync('./data/listings.json', JSON.stringify(ALL_REAL_STARTUPS, null, 2), 'utf8');
  fs.writeFileSync('./src/data/listings.json', JSON.stringify(ALL_REAL_STARTUPS, null, 2), 'utf8');
  fs.writeFileSync('./data/jobs.json', JSON.stringify(REAL_JOBS_DATA, null, 2), 'utf8');
  fs.writeFileSync('./src/data/jobs.json', JSON.stringify(REAL_JOBS_DATA, null, 2), 'utf8');
  console.log('Updated data/listings.json, src/data/listings.json, data/jobs.json, src/data/jobs.json');

  // Push to Firestore
  console.log('Writing to Firestore...');
  const listingsBatch = db.batch();
  for (const item of ALL_REAL_STARTUPS) {
    const ref = db.collection('listings').doc(item.id);
    listingsBatch.set(ref, {
      ...item,
      created_at: new Date().toISOString(),
      updated_at: new Date().toISOString(),
    }, { merge: true });
  }
  await listingsBatch.commit();
  console.log('Committed listings batch to Firestore.');

  const jobsBatch = db.batch();
  for (const job of REAL_JOBS_DATA) {
    const ref = db.collection('jobs').doc(job.id);
    jobsBatch.set(ref, job, { merge: true });
  }
  await jobsBatch.commit();
  console.log('Committed jobs batch to Firestore.');

  // Update stats/public
  const startupsCount = ALL_REAL_STARTUPS.filter((l) => l.type === 'startup').length;
  const incubatorsCount = ALL_REAL_STARTUPS.filter((l) => l.type === 'incubator').length;
  const campusesCount = ALL_REAL_STARTUPS.filter((l) => l.type === 'campus').length;
  const coworkingCount = ALL_REAL_STARTUPS.filter((l) => l.type === 'coworking').length;
  const investorsCount = ALL_REAL_STARTUPS.filter((l) => l.type === 'investor').length;
  const hiringCompanies = new Set(REAL_JOBS_DATA.map((j) => j.listing_id)).size;

  await db.collection('stats').doc('public').set({
    total_listings: ALL_REAL_STARTUPS.length,
    total_startups: startupsCount,
    total_incubators: incubatorsCount,
    total_campuses: campusesCount,
    total_coworking: coworkingCount,
    total_investors: investorsCount,
    total_jobs: REAL_JOBS_DATA.length,
    companies_hiring: hiringCompanies,
    verified_percentage: 100,
    last_synced_at: new Date().toISOString(),
  });
  console.log('Updated public stats doc in Firestore.');
  console.log('Done!');
}

seedAll().catch((err) => {
  console.error('Seed error:', err);
  process.exit(1);
});

