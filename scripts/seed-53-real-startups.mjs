async function seed() {
  console.log(`--- Seeding ${ALL_REAL_STARTUPS.length} real Visakhapatnam startups ---`);

  // Hydrate jobs count into listings
  const enrichedListings = ALL_REAL_STARTUPS.map((listing) => {
    const listingJobs = REAL_JOBS.filter((j) => j.listing_id === listing.id);
    return {
      ...listing,
      jobs_count: listingJobs.length,
      open_jobs: listingJobs,
    };
  });

  // 1. Write local JSON fallback stores
  fs.writeFileSync('data/listings.json', JSON.stringify(enrichedListings, null, 2));
  fs.writeFileSync('src/data/listings.json', JSON.stringify(enrichedListings, null, 2));
  fs.writeFileSync('data/jobs.json', JSON.stringify(REAL_JOBS, null, 2));
  fs.writeFileSync('src/data/jobs.json', JSON.stringify(REAL_JOBS, null, 2));
  console.log('Updated data/listings.json, src/data/listings.json, data/jobs.json, src/data/jobs.json');

  // 2. Sync to Firestore
  console.log('Writing to Firestore...');
  const batch = db.batch();

  // Clear old listings
  const existingListings = await db.collection('listings').get();
  for (const doc of existingListings.docs) {
    batch.delete(doc.ref);
  }

  // Clear old jobs
  const existingJobs = await db.collection('jobs').get();
  for (const doc of existingJobs.docs) {
    batch.delete(doc.ref);
  }

  // Clear old news
  const existingNews = await db.collection('news').get();
  for (const doc of existingNews.docs) {
    batch.delete(doc.ref);
  }

  await batch.commit();
  console.log('Cleared old Firestore documents');

  // Insert new listings in batches of 20
  for (let i = 0; i < enrichedListings.length; i += 20) {
    const subBatch = db.batch();
    const chunk = enrichedListings.slice(i, i + 20);
    for (const listing of chunk) {
      const ref = db.collection('listings').doc(listing.id);
      subBatch.set(ref, listing);
    }
    await subBatch.commit();
  }
  console.log(`Inserted ${enrichedListings.length} listings into Firestore`);

  // Insert jobs
  const jobsBatch = db.batch();
  for (const job of REAL_JOBS) {
    const ref = db.collection('jobs').doc(job.id);
    jobsBatch.set(ref, job);
  }
  await jobsBatch.commit();
  console.log(`Inserted ${REAL_JOBS.length} jobs into Firestore`);

  // Insert news
  const newsBatch = db.batch();
  for (const item of REAL_NEWS) {
    const ref = db.collection('news').doc(item.id);
    newsBatch.set(ref, item);
  }
  await newsBatch.commit();
  console.log(`Inserted ${REAL_NEWS.length} news items into Firestore`);

  // Update stats/public
  const startupsCount = enrichedListings.filter((l) => l.type === 'startup').length;
  const investorsCount = enrichedListings.filter((l) => l.type === 'investor').length;
  const incubatorsCount = enrichedListings.filter((l) => l.type === 'incubator').length;
  const campusesCount = enrichedListings.filter((l) => l.type === 'campus').length;
  const coworkingCount = enrichedListings.filter((l) => l.type === 'coworking').length;
  const hiringCount = enrichedListings.filter((l) => (l.jobs_count || 0) > 0).length;

  const publicStats = {
    total_listings: enrichedListings.length,
    total_startups: startupsCount,
    total_investors: investorsCount,
    total_incubators: incubatorsCount,
    total_campuses: campusesCount,
    total_coworking: coworkingCount,
    total_jobs: REAL_JOBS.length,
    companies_hiring: hiringCount,
    last_updated: new Date().toISOString(),
  };

  await db.collection('stats').doc('public').set(publicStats);
  console.log('Updated stats/public document:', publicStats);

  console.log('--- SEEDING COMPLETE ---');
}

seed().catch(console.error);

