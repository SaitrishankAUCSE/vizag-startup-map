async function seed() {
  console.log(`Seeding ${STARTUPS_DATA.length} Vizag tech ecosystem entities into Firestore...`);
  const batch = db.batch();

  // 1. Listings
  for (const item of STARTUPS_DATA) {
    const docRef = db.collection('listings').doc(item.id);
    const now = new Date().toISOString();
    batch.set(
      docRef,
      {
        ...item,
        created_at: now,
        updated_at: now,
      },
      { merge: true }
    );
  }

  // 2. Jobs
  for (const job of JOBS_DATA) {
    const docRef = db.collection('jobs').doc(job.id);
    batch.set(docRef, job, { merge: true });
  }

  // 3. Stats doc
  const startupsCount = STARTUPS_DATA.filter((l) => l.type === 'startup').length;
  const investorsCount = STARTUPS_DATA.filter((l) => l.type === 'investor').length;
  const incubatorsCount = STARTUPS_DATA.filter((l) => l.type === 'incubator').length;
  const campusesCount = STARTUPS_DATA.filter((l) => l.type === 'campus').length;
  const coworkingCount = STARTUPS_DATA.filter((l) => l.type === 'coworking').length;
  const hiringCompanies = new Set(JOBS_DATA.map((j) => j.listing_id)).size;

  const statsRef = db.collection('stats').doc('public');
  batch.set(
    statsRef,
    {
      total_startups: startupsCount,
      total_investors: investorsCount,
      total_incubators: incubatorsCount,
      total_campuses: campusesCount,
      total_coworking: coworkingCount,
      companies_hiring: hiringCompanies,
      open_roles: JOBS_DATA.length,
      jobs_posted_last_7_days: JOBS_DATA.length,
      new_listings_last_30_days: STARTUPS_DATA.length,
      last_updated_at: new Date().toISOString(),
    },
    { merge: true }
  );

  await batch.commit();
  console.log('✅ Successfully seeded Firestore with approved Vizag startups and jobs!');
}

seed().catch(console.error);
